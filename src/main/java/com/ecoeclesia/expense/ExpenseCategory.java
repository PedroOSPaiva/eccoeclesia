package com.ecoeclesia.expense;

/**
 * Categories supported by the expense module. The vocabulary intentionally
 * matches the language used by the ministries that contributed to the backlog
 * so that reports can be read without a translation layer.
 */
public enum ExpenseCategory {
    GROCERIES,
    TRANSPORT,
    UTILITIES,
    MAINTENANCE,
    ENTERTAINMENT,
    DONATIONS,
    OTHER
}
